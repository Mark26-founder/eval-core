"""Data models for model runners."""

from dataclasses import dataclass

from eval_core.runners.exceptions import RunnerError


@dataclass(frozen=True)
class RunnerResponse:
    """Immutable response returned from a model runner.

    Attributes:
        output: The text output generated by the model.
        latency_ms: Time taken in milliseconds to generate the response.
        input_tokens: Number of input tokens processed.
        output_tokens: Number of output tokens generated.
    """

    output: str
    latency_ms: float
    input_tokens: int
    output_tokens: int

    def __post_init__(self) -> None:
        """Validates response metrics.

        Raises:
            RunnerError: If latency_ms, input_tokens, or output_tokens is negative.
        """
        if self.latency_ms < 0:
            raise RunnerError("latency_ms must be non-negative")
        if self.input_tokens < 0:
            raise RunnerError("input_tokens must be non-negative")
        if self.output_tokens < 0:
            raise RunnerError("output_tokens must be non-negative")
